/* ============================================================
   state.js — 이 사이트의 "상태"를 한곳에 모아둔 파일

   이 과제의 핵심은 화면을 예쁘게 만드는 게 아니라
   "사용자 이벤트 → 상태 변경 → 화면 업데이트" 흐름을 만드는 것이다.

   그래서 규칙을 하나 정했다.
     - 화면에서 달라질 수 있는 값은 전부 아래 state 객체에 적는다.
     - state를 직접 고치는 코드는 각 기능 파일의 "상태 변경 함수"뿐이다.
     - 상태를 고친 뒤에는 반드시 그리는 함수를 부른다.

   이렇게 해두면 "지금 화면이 왜 이 모양인가"를 물었을 때
   DOM을 뒤질 필요 없이 state만 보면 된다.
   ============================================================ */

const state = {
  /* 1. 테마 — 'light' 또는 'dark' */
  theme: 'light',

  /* 2. 모바일 메뉴가 열려 있는지 */
  menuOpen: false,

  /* 3. 스크롤 위치에 따라 달라지는 것 */
  scrolled: false,      // 60px 넘게 내렸는가 → 네비 배경색
  showToTop: false,     // 300px 넘게 내렸는가 → 맨 위로 버튼

  /* 4. GitHub 프로젝트
     status는 네 가지 중 하나만 가진다.
       'loading' 불러오는 중
       'success' 성공
       'error'   실패
       'empty'   성공했지만 보여줄 게 없음 */
  projects: {
    status: 'loading',
    items: [],
    error: '',
  },

  /* 5. 언어 필터 — 'all' 이거나 'Python' 같은 언어 이름 */
  filter: 'all',

  /* 6. 폼 검증 결과
     errors는 { name: '이름을 입력하세요' } 같은 모양이 된다.
     비어 있으면 문제가 없다는 뜻이다. */
  form: {
    errors: {},
    success: '',
  },
};

/* 스크롤 기준값. 과제 문서에 "바꿔도 되지만 README에 명시"라고 되어 있어
   숫자를 코드 여기저기 흩지 않고 여기 모아두고 README에 적었다. */
const SCROLL_NAV = 60;    // 네비게이션 배경색이 바뀌는 지점
const SCROLL_TOP = 300;   // 맨 위로 버튼이 나타나는 지점
const REVEAL_THRESHOLD = 0.2;  // 요소가 20% 보이면 나타나는 애니메이션 시작

